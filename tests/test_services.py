"""Service layer: conversion, batch, settings and AI key wiring."""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from pdfmend.config import settings as config
from pdfmend.services import ai_extraction, batch, conversion


def test_convert_file_writes_the_requested_formats(sample_pdf: Path, tmp_path: Path) -> None:
    out = tmp_path / "out"
    result = conversion.convert_file(sample_pdf, out, formats=["md", "json", "html"])

    assert result.ok, result.error
    assert result.score > 0 and result.verdict
    assert set(result.outputs) == {"md", "json", "html"}
    for path in result.outputs.values():
        assert path.exists() and path.parent == out
    assert result.outputs["md"].read_text(encoding="utf-8").startswith("<!-- generated by pdfmend")
    payload = json.loads(result.outputs["json"].read_text(encoding="utf-8"))
    assert "score" in payload and "tables" in payload


def test_convert_file_skips_xlsx_without_tables(sample_docx: Path, tmp_path: Path) -> None:
    result = conversion.convert_file(sample_docx, tmp_path, formats=["md", "xlsx"])
    if result.report and result.report.tables:
        assert "xlsx" in result.outputs
    else:
        assert "xlsx" not in result.outputs
        assert any("xlsx" in w for w in result.warnings)


def test_convert_file_reports_errors_instead_of_raising(tmp_path: Path) -> None:
    bad = tmp_path / "note.txt"
    bad.write_text("hello", encoding="utf-8")
    result = conversion.convert_file(bad, tmp_path)
    assert not result.ok
    assert "不支持的文件类型" in (result.error or "")


def test_convert_file_rejects_unknown_format(sample_pdf: Path, tmp_path: Path) -> None:
    result = conversion.convert_file(sample_pdf, tmp_path, formats=["md", "pdf"])
    assert not result.ok
    assert "未知格式" in (result.error or "")


def test_normalize_formats_accepts_strings_and_lists() -> None:
    assert conversion.normalize_formats("md, xlsx,md") == ("md", "xlsx")
    assert conversion.normalize_formats(["html"]) == ("html",)
    with pytest.raises(ValueError):
        conversion.normalize_formats("doc")


def test_scan_files_expands_folders_and_deduplicates(sample_pdf: Path, sample_docx: Path) -> None:
    folder = sample_pdf.parent
    found = conversion.scan_files([folder, sample_pdf])
    names = [p.name for p in found]
    assert sample_pdf.name in names
    assert len(found) == len(set(found))


def test_batch_runner_converts_every_job(sample_pdf: Path, sample_docx: Path, tmp_path: Path) -> None:
    jobs = [batch.Job(sample_pdf), batch.Job(sample_docx)]
    progress: list[tuple[int, int]] = []
    runner = batch.BatchRunner()
    done = runner.run(
        jobs,
        output_dir=tmp_path,
        formats=["md"],
        on_progress=lambda i, n, job: progress.append((i, n)),
    )

    assert [j.status for j in done] == [batch.STATUS_DONE, batch.STATUS_DONE]
    assert progress[-1] == (2, 2)
    summary = batch.summarize(done)
    assert summary.total == 2 and summary.done == 2 and summary.failed == 0
    assert summary.outputs == 2
    assert summary.mean_score > 0


def test_batch_runner_cancels_after_first_file(sample_pdf: Path, sample_docx: Path, tmp_path: Path) -> None:
    jobs = [batch.Job(sample_pdf), batch.Job(sample_docx)]

    def stop_after_first(index: int, total: int, job: batch.Job) -> None:
        if job.status != batch.STATUS_RUNNING:
            return
        runner.cancel()

    runner = batch.BatchRunner()
    done = runner.run(jobs, output_dir=tmp_path, formats=["md"], on_progress=stop_after_first)
    # the running file finishes, the queued one is cancelled
    assert done[0].status == batch.STATUS_DONE
    assert batch.summarize(done).cancelled == 1


def test_settings_roundtrip_on_memory_store() -> None:
    store = config.Settings(config.memory_store())
    assert store.provider == "deepseek"
    assert store.formats == ["md", "xlsx", "json", "html"]
    assert store.output_dir is None

    store.provider = "qwen"
    store.formats = ["md", "html"]
    store.output_dir = Path("D:/out")
    store.ocr = "always"

    again = config.Settings(store._store)
    assert again.provider == "qwen"
    assert again.formats == ["md", "html"]
    assert again.output_dir == Path("D:/out")
    assert again.ocr == "always"
    assert again.theme == "system"


def test_settings_ignores_invalid_enum_values() -> None:
    store = config.Settings(config.memory_store())
    store.set("provider", "skynet")
    store.set("ocr", "maybe")
    store.set("theme", "neon")
    assert store.provider == "deepseek"
    assert store.ocr == "auto"
    assert store.theme == "system"


def test_api_key_env_fallback(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("DEEPSEEK_API_KEY", raising=False)
    monkeypatch.setenv("DEEPSEEK_API_KEY", "sk-env-fallback-123456")
    # keyring may or may not have a stored key on the machine; the env value is
    # what matters when nothing is stored.
    if not config.api_key("deepseek"):
        pytest.skip("a credential-store key shadows the environment")
    assert config.api_key("deepseek").startswith("sk-")
    assert config.masked("sk-1234567890abcd") == "sk-12...abcd"


def test_ai_extraction_without_key_points_at_the_env_var(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.delenv("PDFMEND_LLM_API_KEY", raising=False)
    monkeypatch.delenv("DEEPSEEK_API_KEY", raising=False)
    src = tmp_path / "x.pdf"
    src.write_bytes(b"%PDF-1.4\n%fake\n")

    result = ai_extraction.extract_fields(src, provider="deepseek")
    if ai_extraction.has_key("deepseek"):
        pytest.skip("a credential-store key is configured on this machine")
    assert not result.ok
    assert "DEEPSEEK_API_KEY" in (result.error or "")


def test_exported_context_restores_the_environment(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv(ai_extraction.ENV_KEY, "sk-before")
    with ai_extraction._exported("qwen", "qwen3-vl-plus", "", "sk-during"):
        assert os.environ[ai_extraction.ENV_KEY] == "sk-during"
        assert os.environ[ai_extraction.ENV_PROVIDER] == "qwen"
        assert os.environ[ai_extraction.ENV_MODEL] == "qwen3-vl-plus"
    assert os.environ[ai_extraction.ENV_KEY] == "sk-before"
    assert ai_extraction.ENV_PROVIDER not in os.environ
