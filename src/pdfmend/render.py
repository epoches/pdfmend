MONEY_PREFIX = "¥$€£"
PLAIN_NUM = re.compile(r"^[¥$€£]?\s*[-+]?\d{1,3}(,\d{3})*(\.\d+)?$|^[¥$€£]?\s*[-+]?\d+(\.\d+)?$")
PERCENT = re.compile(r"^([-+]?\d+(?:\.\d+)?)\s*%$")
BAD_SHEET = re.compile(r"[\\/*?:\[\]]")


def _cell(value: str) -> str:
    return str(value).replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def markdown_table(rows: list[list[str]], header_rows: int = 1) -> str:
    if not rows:
        return ""
    width = max(len(r) for r in rows)
    rows = [list(r) + [""] * (width - len(r)) for r in rows]
    header_rows = max(1, min(header_rows, len(rows)))
    if header_rows == 1:
        head = rows[0]
        body = rows[1:]
    else:
        head = []
        for j in range(width):
            parts = [rows[i][j] for i in range(header_rows) if rows[i][j]]
            head.append(" / ".join(dict.fromkeys(parts)))
        body = rows[header_rows:]
    out = ["| " + " | ".join(_cell(c) for c in head) + " |",
           "| " + " | ".join("---" for _ in range(width)) + " |"]
    for r in body:
        out.append("| " + " | ".join(_cell(c) for c in r) + " |")
    return "\n".join(out)


def _badge(conf: float) -> str:
    if conf >= 0.85:
        return "高置信"
    if conf >= 0.6:
        return "需抽查"
    return "低置信"


def to_markdown(report: Report) -> str:
    doc = report.document
    out: list[str] = []
    out.append("<!-- generated by pdfmend %s -->" % report.to_dict()["version"])
    out.append(
        "> **质量分 %d/100 · %s** — %s"
        % (report.score, report.verdict, "；".join(report.reasons))
    )
    if report.tables:
        out.append("")
        out.append(
            "> %d 张表：%s"
            % (
                len(report.tables),
                "，".join(
                    "表%d %s（%s）" % (i, _badge(t.confidence), t.shape)
                    for i, t in enumerate(report.tables, 1)
                ),
            )
        )
    out.append("")

    for block in doc.blocks:
        if block.kind == "page":
            if block.page and doc.pages > 1:
                out.append(f"<!-- page {block.page} -->")
                out.append("")
        elif block.kind == "heading":
            level = max(1, min(6, block.level or 1))
            out.append("#" * level + " " + block.text)
            out.append("")
        elif block.kind == "para":
            out.append(block.text)
            out.append("")
        elif block.kind == "table" and block.table:
            t = block.table
            where = f"第 {t.page} 页，" if t.page else ""
            out.append(f"**表 {t.id}**（{where}{t.shape}，置信度 {t.confidence:.2f}）")
            if t.flags:
                out.append("`" + "` `".join(t.flags) + "`")
            out.append("")
            out.append(markdown_table(t.rows, t.header_rows))
            out.append("")

    if report.reasons:
        out.append("---")
        out.append("**pdfmend 提醒**：" + "；".join(report.reasons))
    return "\n".join(out).strip() + "\n"


def _to_number(value: str) -> tuple[float | int, str] | None:
    v = value.strip()
    if not v:
        return None
    m = PERCENT.match(v)
    if m:
        return float(m.group(1)) / 100.0, "0.00%"
    if PLAIN_NUM.match(v):
        try:
            n = float(v.lstrip(MONEY_PREFIX).replace(",", "").replace(" ", ""))
        except ValueError:
            return None
        if n.is_integer() and abs(n) < 1e15:
            return int(n), "General"
        return n, "General"
    return None


def _sheet_name(base: str, used: set[str]) -> str:
    name = BAD_SHEET.sub("_", base).strip() or "Sheet"
    name = name[:31]
    candidate = name
    i = 2
    while candidate.lower() in used:
        suffix = f"_{i}"
        candidate = name[: 31 - len(suffix)] + suffix
        i += 1
    used.add(candidate.lower())
    return candidate


def to_xlsx(report: Report, path: Path) -> Path:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    doc = report.document
    wb = Workbook()
    ws = wb.active
    ws.title = "_report"
    head_font = Font(bold=True)
    warn_fill = PatternFill("solid", fgColor="FFF2CC")
    bad_fill = PatternFill("solid", fgColor="FCE4E4")

    ws.append(["pdfmend 报告"])
    ws["A1"].font = Font(bold=True, size=14)
    rows = [
        ("文件", doc.path.name),
        ("格式", doc.kind),
        ("页数", doc.pages),
        ("质量分", report.score),
        ("结论", report.verdict),
        ("提醒", "；".join(report.reasons)),
        ("扫描页（未 OCR）", ", ".join(map(str, doc.scanned_pages)) or "无"),
        ("", ""),
        ("表", "工作表"),
        ("位置", "页"),
        ("形状", "行列"),
        ("置信度", "标记"),
    ]
    for r in rows:
        ws.append(list(r))
    for cell in ws[9]:
        cell.font = head_font
    for t in report.tables:
        ws.append([t.id, t.id, t.page or "", t.shape, round(t.confidence, 3), ",".join(t.flags)])
    ws.column_dimensions["A"].width = 18
    ws.column_dimensions["B"].width = 22
    ws.column_dimensions["C"].width = 10
    ws.column_dimensions["D"].width = 16
    ws.column_dimensions["E"].width = 18

    used: set[str] = set()
    bases: dict[str, str] = {}
    last_heading = ""
    for block in doc.blocks:
        if block.kind == "heading":
            last_heading = block.text.strip()
        elif block.kind == "table" and block.table:
            bases[block.table.id] = last_heading or f"表{block.table.id}"

    for i, t in enumerate(report.tables, 1):
        if not t.rows:
            continue
        title = bases.get(t.id, f"表{t.id}")
        name = _sheet_name(f"{i:02d} {title}", used)
        sh = wb.create_sheet(name)
        hdr = max(1, t.header_rows)
        for r_idx, row in enumerate(t.rows, 1):
            for c_idx, raw in enumerate(row, 1):
                value = raw
                fmt = None
                if r_idx > hdr:
                    conv = _to_number(raw)
                    if conv is not None:
                        value, fmt = conv
                cell = sh.cell(row=r_idx, column=c_idx, value=value)
                cell.alignment = Alignment(vertical="top", wrap_text=True)
                if fmt and fmt != "General":
                    cell.number_format = fmt
                if r_idx <= hdr:
                    cell.font = head_font
        ncols = max((len(r) for r in t.rows), default=1)
        if t.confidence < 0.6:
            fill = bad_fill
        elif t.flags:
            fill = warn_fill
        else:
            fill = None
        if fill is not None:
            for r_idx in range(1, hdr + 1):
                for c_idx in range(1, ncols + 1):
                    sh.cell(row=r_idx, column=c_idx).fill = fill
        sh.freeze_panes = f"A{hdr + 1}"
        widths = {}
        for row in t.rows:
            for c_idx, v in enumerate(row, 1):
                widths[c_idx] = max(widths.get(c_idx, 6), min(60, len(str(v)) + 2))
        for c_idx, w in widths.items():
            sh.column_dimensions[get_column_letter(c_idx)].width = w

    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(path))
    return path


def to_json(report: Report, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(report.to_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return path


