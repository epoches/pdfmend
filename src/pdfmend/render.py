def to_html(report: Report) -> str:
    doc = report.document
    cls = "ok" if report.score >= 85 else ("warn" if report.score >= 60 else "bad")
    parts = [
        "<!doctype html><html lang='zh-CN'><head><meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width,initial-scale=1'>",
        f"<title>{html.escape(doc.path.name)} · pdfmend</title><style>{CSS}</style></head><body>",
        f"<h1>{html.escape(doc.path.name)}</h1>",
        f"<div class='sub'>pdfmend {report.to_dict()['version']} · {doc.kind.upper()} · "
        f"{doc.pages} 页 · {len(report.tables)} 张表</div>",
        f"<div>质量分 <span class='score {cls}'>{report.score}/100 · "
        f"{html.escape(report.verdict)}</span></div>",
        f"<div class='note'>{html.escape('；'.join(report.reasons))}</div>",
    ]
    for block in doc.blocks:
        if block.kind == "heading":
            lvl = max(2, min(6, (block.level or 1) + 1))
            parts.append(f"<h{lvl}>{html.escape(block.text)}</h{lvl}>")
        elif block.kind == "para":
            for line in block.text.splitlines():
                parts.append(f"<p>{html.escape(line)}</p>")
        elif block.kind == "table" and block.table:
            t = block.table
            badge = "ok" if t.confidence >= 0.85 else ("warn" if t.confidence >= 0.6 else "bad")
            where = f"第 {t.page} 页 · " if t.page else ""
            parts.append(
                f"<div class='cap'>表 {html.escape(t.id)} · {where}{t.shape} · "
                f"<span class='score {badge}'>{t.confidence:.2f}</span></div>"
            )
            if t.flags:
                parts.append("<div class='flags'>" + "".join(
                    f"<span class='flag'>{html.escape(f)}</span>" for f in t.flags) + "</div>")
            parts.append("<table><thead>")
            hdr = max(1, min(t.header_rows, len(t.rows) or 1))
            for row in t.rows[:hdr]:
                parts.append("<tr>" + "".join(f"<th>{html.escape(c)}</th>" for c in row) + "</tr>")
            parts.append("</thead><tbody>")
            for row in t.rows[hdr:]:
                parts.append("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in row) + "</tr>")
            parts.append("</tbody></table>")
    parts.append("</body></html>")
    return "".join(parts)


def write_html(report: Report, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(to_html(report), encoding="utf-8")
    return path
